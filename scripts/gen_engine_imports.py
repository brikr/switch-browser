"""Generate runtime-bound trampolines for engine symbols the host code calls.

The host is compiled against the WKC headers, but the engine's code only exists after the loader
maps the NROs. For each undefined engine symbol in the host objects (from `nm -u`), this emits an
AArch64 trampoline that jumps through a slot; the loader fills the slots after linking.

Usage: aarch64-linux-gnu-nm -u host/*.o | python3 -I scripts/gen_engine_imports.py > engine_imports.S
"""
import re
import sys

# Engine-defined symbols: the WKC namespace (functions and the odd static) and C-level wkc* APIs.
ENGINE = re.compile(r"^(_ZN3WKC|_ZNK3WKC|_ZThn\d+_N3WKC|wkc|WKC|JS[A-Z])")
# Things the host may reference that would be data, not code; we refuse rather than mis-bind.
DATA = re.compile(r"^_Z(TV|TI|TS)")


def main():
    names = sorted({line.split()[-1] for line in sys.stdin if line.strip() and ENGINE.match(line.split()[-1])})
    data = [n for n in names if DATA.match(n)]
    if data:
        sys.exit("engine data symbols referenced by host (unsupported): " + ", ".join(data))

    out = [
        "// Generated by scripts/gen_engine_imports.py. Do not edit.",
        "    .text",
        "    .balign 4",
    ]
    for i, n in enumerate(names):
        out += [
            f"    .global {n}",
            f"    .type {n}, %function",
            f"{n}:",
            "    adrp x16, nxb_engine_import_slots",
            "    add x16, x16, :lo12:nxb_engine_import_slots",
            f"    ldr x16, [x16, #{i * 8}]",
            "    br x16",
            f"    .size {n}, .-{n}",
        ]
    out += [
        "",
        "    .data",
        "    .balign 8",
        "    .global nxb_engine_import_slots",
        "nxb_engine_import_slots:",
        f"    .zero {max(len(names), 1) * 8}",
        "",
        "    .section .rodata",
        "    .balign 8",
        "    .global nxb_engine_import_names",
        "nxb_engine_import_names:",
    ]
    out += [f"    .quad .Lname{i}" for i in range(len(names))]
    out += [
        "    .global nxb_engine_import_count",
        "nxb_engine_import_count:",
        f"    .quad {len(names)}",
    ]
    out += [f'.Lname{i}: .asciz "{n}"' for i, n in enumerate(names)]
    print("\n".join(out))


if __name__ == "__main__":
    main()
